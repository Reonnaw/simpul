-- BAGIAN 5: cek jumlah baris (harus sama dengan Tabel 3.18, total 77 baris)
USE simlog_db;
SELECT 'KANTOR_CABANG' AS tabel, COUNT(*) AS jumlah_baris FROM KANTOR_CABANG
UNION ALL SELECT 'PELANGGAN', COUNT(*) FROM PELANGGAN
UNION ALL SELECT 'KENDARAAN', COUNT(*) FROM KENDARAAN
UNION ALL SELECT 'PENGEMUDI', COUNT(*) FROM PENGEMUDI
UNION ALL SELECT 'SERTIFIKASI_PENGEMUDI', COUNT(*) FROM SERTIFIKASI_PENGEMUDI
UNION ALL SELECT 'JADWAL_CUTI_PENGEMUDI', COUNT(*) FROM JADWAL_CUTI_PENGEMUDI
UNION ALL SELECT 'OTORISASI_OPERASIONAL', COUNT(*) FROM OTORISASI_OPERASIONAL
UNION ALL SELECT 'PENUGASAN_ARMADA', COUNT(*) FROM PENUGASAN_ARMADA
UNION ALL SELECT 'PENGIRIMAN', COUNT(*) FROM PENGIRIMAN
UNION ALL SELECT 'DETAIL_BARANG', COUNT(*) FROM DETAIL_BARANG
UNION ALL SELECT 'RUTE_TRANSIT', COUNT(*) FROM RUTE_TRANSIT
UNION ALL SELECT 'FAKTUR', COUNT(*) FROM FAKTUR
UNION ALL SELECT 'ASURANSI', COUNT(*) FROM ASURANSI
UNION ALL SELECT 'ARSIP_PENGIRIMAN', COUNT(*) FROM ARSIP_PENGIRIMAN;
